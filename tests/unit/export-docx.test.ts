import { describe, it, expect } from "vitest";
import { unzipSync, strFromU8 } from "fflate";
import { buildDocx } from "@/lib/export/docx";
import type { ExportModel } from "@/lib/domain/export";

const model: ExportModel = {
  title: "Sprint 24 Retro",
  dateLabel: "20 Nov 2026",
  isoDate: "2026-11-20",
  facilitator: "Ali",
  participants: [
    { name: "Ali", role: "Scrum Master" },
    { name: "Lina", role: "PO" },
  ],
  stats: { participants: 2, cards: 3, votes: 7, actions: 1 },
  sections: [
    {
      heading: "What went well",
      items: [
        { text: "Tom & Jerry <3 🎉", votes: 4 },
        { text: "التعاون كان ممتاز", votes: 1 },
      ],
    },
    { heading: "What could be improved", items: [{ text: "Flaky CI pipeline", votes: 2 }] },
    { heading: "Ideas", items: [] },
  ],
  actions: [{ text: "Fix the flaky CI step", owner: "Omar", due: "27 Nov 2026", from: ["Flaky CI pipeline"] }],
};

async function xml(m: ExportModel): Promise<string> {
  const blob = await buildDocx(m);
  const files = unzipSync(new Uint8Array(await blob.arrayBuffer()));
  return strFromU8(files["word/document.xml"]);
}

/** the <w:p> … </w:p> that contains `text` */
function paragraphOf(doc: string, text: string): string {
  const at = doc.indexOf(text);
  expect(at, text).toBeGreaterThan(-1);
  const start = Math.max(doc.lastIndexOf("<w:p>", at), doc.lastIndexOf("<w:p ", at));
  return doc.slice(start, doc.indexOf("</w:p>", at));
}

describe("buildDocx", () => {
  it("uses real Word headings and the English Confluence sections", async () => {
    const doc = await xml(model);
    expect(doc).toContain('w:val="Heading1"');
    expect(doc).toContain('w:val="Heading2"');
    for (const s of [
      "Sprint 24 Retro",
      "Date",
      "20 Nov 2026",
      "Facilitator",
      "Participants",
      "At a glance",
      "What went well",
      "What could be improved",
      "Ideas",
      "Action items",
      "Generated by Fox Retro",
    ])
      expect(doc, s).toContain(s);
  });

  it("lists participants with roles", async () => {
    const doc = await xml(model);
    expect(doc).toContain("Lina");
    expect(doc).toContain("PO");
  });

  it("escapes XML characters and keeps emoji", async () => {
    expect(await xml(model)).toContain("Tom &amp; Jerry &lt;3 🎉");
  });

  it("sets Arabic cards right-to-left, English ones not", async () => {
    const doc = await xml(model);
    expect(paragraphOf(doc, "التعاون كان ممتاز")).toContain("<w:bidi");
    expect(paragraphOf(doc, "Flaky CI pipeline</w:t>")).not.toContain("<w:bidi");
  });

  it("puts actions in a table with a checkbox per row", async () => {
    const doc = await xml(model);
    const table = doc.slice(doc.indexOf("Action items"));
    for (const h of ["Action", "Owner", "Due", "From"]) expect(table).toContain(`>${h}</w:t>`);
    expect(table).toContain("☐");
    expect(table).toContain("Fix the flaky CI step");
    expect(table).toContain("Omar");
    expect(table).toContain("27 Nov 2026");
  });

  it("handles an empty retro", async () => {
    const doc = await xml({
      ...model,
      sections: model.sections.map((s) => ({ ...s, items: [] })),
      actions: [],
    });
    expect(doc).toContain("None");
    expect(doc).toContain("No action items.");
  });
});
